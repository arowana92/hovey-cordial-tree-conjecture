"""Two-star attachments on a one-surplus core at prime powers."""
from math import gcd

from .two_star_growth import leaf_suffix
from .two_star_moduli import generator, prime_powers
from .two_star_surplus import packet, prime_growth, split


def complete(k,s,size,x,y,leaves,excluded=()):
    index = k//size
    cosets = [i for i in range(1,index) if i not in excluded]
    needed = (s-1-len(leaves))//size
    assert 0<=needed<=len(cosets)
    for i in cosets[:needed]:
        leaves.update(range(i,k,index))
    assert len(leaves)==s-1 and not leaves.intersection({x,y,0})
    return split(k,x,y,leaves)


def two_intervals(k,s,a,size,h,left,right):
    # The intervals end just before a and just before zero in h-coordinates.
    assert left>=0 and right>=0
    leaves = {(a-i*h)%k for i in range(1,left+1)}
    leaves.update((-i*h)%k for i in range(1,right+1))
    return complete(k,s,size,(a+h)%k,a,leaves)


def separated(k,s,a,b,size):
    if s>k-1-s:
        return separated(k,k-1-s,b,a,size)[::-1]
    h = (a-b)%k
    tail = (s-2)%size
    leaves = {b}|{(-i*h)%k for i in range(1,tail+1)}
    return complete(k,s,size,(a+h)%k,a,leaves,{a%(k//size)})


def interior(k,s,a,b,size,m):
    width = size//m
    r = s%size
    index = k//size
    if min(r,size-1-r)<=width:
        if r<=width:
            return interior(k,k-1-s,b,a,size,m)[::-1]
        h = generator(k,size,width,b-a)
        pos = (a//index)*pow(h//index,-1,size)%size
        right = size-pos-width
        return two_intervals(k,s,a,size,h,r-1-right,right)
    h = generator(k,size,width,a-b)
    pos = (a//index)*pow(h//index,-1,size)%size
    if pos>size-r+width-1:
        return interior(k,k-1-s,b,a,size,m)[::-1]
    return two_intervals(k,s,a,size,h,width,r-1-width)


def antipodes(k,s,a,b,size):
    width = size//(k//gcd(b,k))
    r = s%size
    if r<=size//2:
        h = generator(k,size,width,-b)
        return two_intervals(k,s,a,size,h,r-1-width,width)
    h = generator(k,size,width,b)
    return two_intervals(k,s,a,size,h,size//2,r-1-size//2)


def full(k,s,a,b):
    """Use every nonzero residue, or return None in the singleton obstruction."""
    (p,_), = prime_powers(k)
    t = k-1-s
    if min(s,t)<1:
        raise ValueError('expected two nonempty stars on k-1 vertices')
    a,b = a%k,b%k
    if not a or not b or a==b or min(s,t)==1:
        return packet(k,s,a,b)
    index = gcd(a-b,k)
    m = k//index
    if m>=3 and a%index:
        return separated(k,s,a,b,m)
    # For antipodes use the group generated by both sites. Both generate it
    # because k is a power of two and the sites are distinct and nonzero.
    base = k//gcd(a,k) if m==2 else m
    r = s%base
    if 1<=r<=base-2:
        idx = k//base
        if m==2 and min(r,base-1-r)>1:
            return antipodes(k,s,a,b,base)
        local = packet(base,r,a//idx,b//idx)
        x,y = (side[0]*idx for side in local)
        return complete(k,s,base,x,y,{v*idx for v in local[0][1:]})
    divisible = s if r==0 else t
    size = p*gcd(divisible,k)
    if m==2:
        if s%size!=size//2:
            return antipodes(k,t,b,a,size)[::-1]
        return antipodes(k,s,a,b,size)
    return interior(k,s,a,b,size,m)


def obstruction(k,s,a,b):
    return k%2==0 and ((s==1 and a==0 and b%2==1) or
                        (s==k-2 and b==0 and a%2==1))


def grow(k,s,t,a,b,surplus=0):
    """Some parent-first order and labels, cordial at every prefix."""
    if min(s,t)<1:
        raise ValueError('expected two nonempty stars')
    if k==2:
        order = [0]*s+[1]*t
        return list(zip(order,prime_growth(k,order,a,b,surplus,surplus=True)))
    a,b = (a-surplus)%k,(b-surplus)%k
    if s+t<=k-1:
        options = range(s,k-t)
    else:
        options = range(max(1,k-1-t),min(s,k-2)+1)
    j = next((i for i in options if not obstruction(k,i,a,b)),None)
    if j is None:
        if s+t==k-1:
            return None
        if t==1:
            result = grow(k,t,s,b,a)
            return [(1-side,(z+surplus)%k) for side,z in result]
        assert s==1 and a==0 and b%2 and t>=k-1
        block = [[],[b]+[i for i in range(1,k) if i!=b]]
        centers = [0,b]  # the postponed singleton attaches at the old zero
    else:
        block = full(k,j,a,b)
        block = [block[0][:s],block[1][:t]]
        centers = [side[0] for side in block]
    result = [(i,z) for i,side in enumerate(block) for z in side]
    if len(result)<s+t:
        weights = {(old+side[0])%k for old,side in zip((a,b),block) if side}
        weights.update((side[0]+z)%k for side in block for z in side[1:])
        gap, = set(range(k))-weights
        pending = [0]*(s-len(block[0]))+[1]*(t-len(block[1]))
        result.extend(leaf_suffix(k,pending,centers,gap))
    return [(i,(z+surplus)%k) for i,z in result]
